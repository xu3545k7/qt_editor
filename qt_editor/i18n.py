def set_lang(lang: str) -> None:
    """設定目前語言（'zh_tw' / 'zh_cn' / 'en'）。"""
    global _LANG
    if lang in _STRINGS:
        _LANG = lang


def get_lang() -> str:
    return _LANG


def t(key: str, *args) -> str:
    """取得翻譯字串，可帶格式化參數。"""
    table = _STRINGS.get(_LANG, _STRINGS['zh_tw'])
    s = table.get(key, _STRINGS['zh_tw'].get(key, key))
    if args:
        try:
            return s.format(*args)
        except Exception:
            return s
    return s
